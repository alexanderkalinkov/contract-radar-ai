// Writes the Supabase Auth email templates to supabase/templates/*.html, plus a README with the subjects.
// Run: npm run email:templates   (set EMAIL_BRAND_NAME to rebrand)
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { authTemplates } from "../src/lib/email/auth-templates";

const dir = join(process.cwd(), "supabase", "templates");
mkdirSync(dir, { recursive: true });
const list = authTemplates(process.env.EMAIL_BRAND_NAME || "Contract Radar");
for (const t of list) writeFileSync(join(dir, t.file), t.html + "\n");

const readme = `# Supabase Auth email templates

Generated by \`npm run email:templates\` from \`src/lib/email/auth-templates.ts\`. Don't edit these files by hand.

Paste each one into Supabase: **Authentication → Emails → Templates**. For each template, set the subject,
switch the body to **Source**, replace everything with the file's contents and save.

| Supabase template | Subject | File |
| --- | --- | --- |
${list.map((t) => `| ${t.label} | ${t.subject} | [${t.file}](./${t.file}) |`).join("\n")}

The logo and footer links use \`{{ .SiteURL }}\`, so set **Authentication → URL Configuration → Site URL** to
the app's address (today https://contract-radar-ai.vercel.app, later your real domain). Nothing else needs changing
when the domain changes.
`;
writeFileSync(join(dir, "README.md"), readme);
console.log(`Wrote ${list.length} templates to ${dir}`);
